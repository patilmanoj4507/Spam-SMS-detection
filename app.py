
import streamlit as st
import pickle
import os

# -------------------------------
# Page Configuration
# -------------------------------
st.set_page_config(
    page_title="Spam SMS Detector",
    page_icon="📩",
    layout="centered"
)

# -------------------------------
# Custom CSS
# -------------------------------
st.markdown("""
<style>
.stApp {
    background: linear-gradient(135deg, #101827, #1e293b);
    color: white;
}

.title {
    text-align: center;
    font-size: 42px;
    font-weight: bold;
    color: #60a5fa;
}

.subtitle {
    text-align: center;
    font-size: 17px;
    color: #cbd5e1;
}

.result-box {
    padding: 22px;
    border-radius: 12px;
    text-align: center;
    font-size: 24px;
    font-weight: bold;
    margin-top: 20px;
}

.spam {
    background-color: #7f1d1d;
    color: #fecaca;
    border: 2px solid #ef4444;
}

.ham {
    background-color: #14532d;
    color: #bbf7d0;
    border: 2px solid #22c55e;
}

.info {
    background-color: #1e3a5f;
    color: #dbeafe;
    padding: 15px;
    border-radius: 10px;
}
</style>
""", unsafe_allow_html=True)

# -------------------------------
# Load Trained Model
# -------------------------------
MODEL_PATH = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "spam_model.pkl"
)

@st.cache_resource
def load_model():
    with open(MODEL_PATH, "rb") as file:
        return pickle.load(file)

# -------------------------------
# Application Header
# -------------------------------
st.markdown(
    '<div class="title">📩 Spam SMS Detector</div>',
    unsafe_allow_html=True
)

st.markdown(
    '<div class="subtitle">'
    'AI-powered SMS classification using Machine Learning'
    '</div>',
    unsafe_allow_html=True
)

st.divider()

# -------------------------------
# Model Availability
# -------------------------------
if not os.path.exists(MODEL_PATH):
    st.error(
        "Trained model not found. Please run train_model.py first."
    )
    st.stop()

try:
    model = load_model()
except Exception as error:
    st.error(f"Unable to load the model: {error}")
    st.stop()

# -------------------------------
# Sample Messages
# -------------------------------
st.subheader("📝 Try a Sample Message")

sample_messages = {
    "Choose a sample": "",
    "Spam SMS": (
        "Congratulations! You have won a free prize. "
        "Call now to claim your reward!"
    ),
    "Legitimate SMS": (
        "Hey, are we meeting at college tomorrow? "
        "Please let me know."
    ),
    "Bank Alert": (
        "Your account has been credited with Rs. 500. "
        "Your available balance has been updated."
    ),
    "Promotional SMS": (
        "URGENT! You have won a cash prize. "
        "Click here to claim your reward now!"
    )
}

selected_sample = st.selectbox(
    "Select an example:",
    list(sample_messages.keys())
)

# -------------------------------
# SMS Input
# -------------------------------
st.subheader("✉️ Enter Your SMS")

sms_text = st.text_area(
    "SMS Message",
    value=sample_messages[selected_sample],
    height=150,
    placeholder="Paste or type your SMS message here...",
    help="Enter the complete message you want to check."
)

# -------------------------------
# Prediction
# -------------------------------
if st.button("🔍 Detect Spam", use_container_width=True):

    if not sms_text.strip():
        st.warning("Please enter an SMS message first.")

    else:
        try:
            prediction = model.predict([sms_text])[0]

            # The training script uses ham/spam labels.
            normalized_prediction = str(prediction).strip().lower()

            st.divider()
            st.subheader("📊 Prediction Results")

            if normalized_prediction in ("spam", "1"):
                st.markdown(
                    '<div class="result-box spam">'
                    '🚨 SPAM SMS DETECTED'
                    '</div>',
                    unsafe_allow_html=True
                )

                st.warning(
                    "This message appears suspicious. "
                    "Avoid clicking unknown links or sharing "
                    "personal information."
                )

            elif normalized_prediction in ("ham", "legitimate", "0"):
                st.markdown(
                    '<div class="result-box ham">'
                    '✅ LEGITIMATE SMS'
                    '</div>',
                    unsafe_allow_html=True
                )

                st.success(
                    "The model classifies this message as legitimate."
                )

            else:
                st.info(
                    f"Predicted class: {prediction}"
                )

            st.caption(
                "Prediction generated by your trained "
                "machine learning model."
            )

        except Exception as error:
            st.error(f"Prediction failed: {error}")

# -------------------------------
# Sidebar
# -------------------------------
with st.sidebar:
    st.title("📩 Spam Detector")

    st.markdown("### How it works")

    st.write("1. Enter an SMS message.")
    st.write("2. TF-IDF converts text into numerical features.")
    st.write("3. The trained classifier predicts the message category.")
    st.write("4. View the prediction result.")

    st.divider()

    st.markdown("### Technologies Used")

    st.write("- Python")
    st.write("- Streamlit")
    st.write("- Scikit-learn")
    st.write("- TF-IDF")
    st.write("- Machine Learning")

    st.divider()

    st.caption("Spam SMS Detection Project")
    st.caption("Educational use only.")

st.divider()

st.caption(
    "Note: Machine learning predictions are not guaranteed "
    "to be correct. Always use caution with suspicious messages."
)
